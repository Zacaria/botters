import { test } from 'node:test'
import assert from 'node:assert/strict'
import { runtime, client, ORIGIN } from './helpers/cloudflare.js'

test('workerd: pending pairing honors bounded HTTP polling without a match queue lock', {timeout:10000},async t=>{
  const {mf}=await runtime();t.after(()=>mf.dispose())
  const c=client(mf),pair=(await c.call('POST','/agent/pair',{})).body
  await c.call('GET',`/agent/poll?token=${pair.agentToken}`)
  const start=performance.now(),poll=await c.call('GET',`/agent/poll?token=${pair.agentToken}&timeout=1`)
  assert.equal(poll.body.approved,false)
  assert.ok(performance.now()-start>=900,'The transport must honor timeout instead of busy-polling')
})

test('workerd: verified accounts, unique live ticket, consent, two-player room and result', { timeout: 60000 }, async t => {
  const { mf, db, mail } = await runtime(); t.after(() => mf.dispose())
  const alice = client(mf), bob = client(mf)
  const signup = await alice.signUp('Alice')
  assert.equal(signup.status, 200, JSON.stringify(signup.body))
  assert.equal((await alice.call('POST', '/session', {})).status, 401)
  assert.equal(mail.length, 1)
  const verify = new URL(mail[0].text.match(/http:\/\/[^\s]+/)[0])
  assert.equal((await alice.call('GET', verify.pathname + verify.search)).status, 302)
  assert.equal((await alice.call('GET', '/account')).body.user.name, 'Alice')
  assert.equal((await bob.signUp('Bob')).status, 200)
  const verifyB = new URL(mail[1].text.match(/http:\/\/[^\s]+/)[0])
  await bob.call('GET', verifyB.pathname + verifyB.search)
  const a = (await alice.call('POST', '/session', {})).body, b = (await bob.call('POST', '/session', {})).body
  assert.equal(typeof a.humanToken, 'string')
  const requests = await Promise.all([alice.call('POST', '/exchange', { ticket: a.liveTicket }), alice.call('POST', '/exchange', { ticket: a.liveTicket })])
  assert.deepEqual(requests.map(r => r.status).sort(), [200, 401])
  assert.equal((await bob.call('POST', '/exchange', { ticket: b.liveTicket })).status, 200)
  assert.equal((await bob.call('GET', `/lobby?token=${a.humanToken}`)).status, 401)
  const pair = (await alice.call('POST', '/agent/pair', { setup: 'local MCP' })).body
  assert.equal((await alice.call('GET', `/agent/poll?token=${pair.agentToken}`)).body.approved, false)
  assert.equal((await alice.call('POST', `/agent/approve?token=${a.humanToken}`, { id: pair.id })).status, 200)
  assert.equal((await alice.call('GET', `/agent/poll?token=${pair.agentToken}`)).body.approved, true)
  assert.equal((await alice.call('POST', `/play?token=${pair.agentToken}`, {})).status, 401)
  const room = await alice.call('POST', `/rooms?token=${a.humanToken}`, { minutes: 3, planets: 16, planning: 10, withAgent: true })
  assert.equal(room.status, 200, JSON.stringify(room.body))
  assert.equal((await bob.call('POST', `/rooms/join?token=${b.humanToken}`, { code: room.body.code })).status, 200)
  assert.equal((await alice.call('POST', `/rooms/start?token=${a.humanToken}`, {})).status, 200)
  const next = await alice.call('GET', `/next?token=${pair.agentToken}`)
  assert.equal(typeof next.body.match?.id, 'string', JSON.stringify(next.body))
  assert.equal((await alice.call('POST', `/input?token=${pair.agentToken}`, { gambits: [{ if: 'always', then: 'hold', on: true }] })).status, 200)
  const state = await alice.call('GET', `/state?token=${a.humanToken}`)
  assert.equal(state.status, 200, JSON.stringify(state.body))
  const before = performance.now()
  const socketResponse = await mf.dispatchFetch(ORIGIN + `/socket?token=${a.humanToken}`, { headers: { upgrade: 'websocket', origin: ORIGIN, cookie: [...alice.cookies].map(([k,v]) => `${k}=${v}`).join('; ') } })
  assert.equal(socketResponse.status, 101)
  const ws = socketResponse.webSocket; ws.accept()
  const frame = await new Promise((resolve, reject) => { ws.addEventListener('message', e => resolve(JSON.parse(e.data)), { once: true }); setTimeout(() => reject(new Error('No real WebSocket frame')), 5000).unref() })
  assert.equal(frame.view?.side, state.body.view.side)
  assert.ok(performance.now() - before < 5000)
  ws.close()
  assert.equal((await alice.call('POST', `/surrender?token=${a.humanToken}`, {})).status, 200)
  const lobby = await alice.call('GET', `/lobby?token=${a.humanToken}`)
  assert.equal(lobby.body.history.length, 1)
  assert.equal((await bob.call('GET', `/lobby?token=${b.humanToken}`)).body.history.length, 1)
  await alice.call('GET', `/state?token=${a.humanToken}`)
  await bob.call('GET', `/state?token=${b.humanToken}`)
  assert.equal((await alice.call('GET', `/lobby?token=${a.humanToken}`)).body.history.length, 1)
  const ratings = await db.prepare("SELECT value FROM game_records WHERE key LIKE 'verified:elo:%'").all()
  assert.deepEqual(ratings.results.map(r => JSON.parse(r.value).games), [1,1])
})
